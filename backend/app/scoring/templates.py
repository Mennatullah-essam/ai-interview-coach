SKILL_LABELS = {
    "communication": "Communication",
    "relevance": "Relevance",
    "structure": "Structure",
    "clarity": "Clarity",
    "technical_depth": "Technical Depth",
}
SKILL_ORDER = ["communication", "relevance", "structure", "clarity", "technical_depth"]

_RECOMMENDATION = {
    "communication": "Practise answering out loud in one to two minutes, with a summary sentence first.",
    "relevance": "Answer the exact question first, then add context; avoid drifting into unrelated details.",
    "structure": "Structure every answer with STAR: situation, task, action and a measurable result.",
    "clarity": "Use shorter sentences and cut repetition so each point is easy to follow.",
    "technical_depth": "Cover the key concepts explicitly and support them with metrics and named tools.",
}
_ADDITIONAL_STRENGTH = {
    "communication": "Clear, well-paced communication",
    "relevance": "Answers that stay focused on the question",
    "structure": "Well-structured answers with clear results",
    "clarity": "Concise, easy-to-follow explanations",
    "technical_depth": "Good coverage of the key concepts",
}
_ADDITIONAL_IMPROVEMENT = {
    "communication": "Overall delivery of answers",
    "relevance": "Staying on topic",
    "structure": "Ending answers with a measurable result",
    "clarity": "Keeping answers concise",
    "technical_depth": "Covering key points and quantifying impact",
}


def interview_texts(breakdown: dict[str, int]) -> tuple[str, str, list[str]]:
    """Return (additional_strength, additional_improvement, three recommendations)."""
    ascending = sorted(SKILL_ORDER, key=lambda k: (breakdown[k], SKILL_ORDER.index(k)))
    descending = sorted(SKILL_ORDER, key=lambda k: (-breakdown[k], SKILL_ORDER.index(k)))
    recommendations = [_RECOMMENDATION[k] for k in ascending[:3]]
    return _ADDITIONAL_STRENGTH[descending[0]], _ADDITIONAL_IMPROVEMENT[ascending[0]], recommendations
