@dataclass
class AnswerFeedback:
    strengths: list[str]
    weaknesses: list[str]
    tip: str
    suggestions: list[str] = field(default_factory=list)


def _variant(key: str, question_type: QuestionType, table: dict) -> str:
    behavioral_key = f"{key}_behavioral"
    if question_type is QuestionType.BEHAVIORAL and behavioral_key in table:
        return table[behavioral_key]
    return table[key]


def answer_feedback(*, dimensions, signals, question_type: QuestionType, thresholds: dict) -> AnswerFeedback:
    scored = [(d.key, d.score) for d in dimensions if d.score is not None and d.weight > 0]
    strong, weak = thresholds["strong"], thresholds["weak"]
    ordered_high = sorted(scored, key=lambda kv: kv[1], reverse=True)
    ordered_low = sorted(scored, key=lambda kv: kv[1])

    strengths = [_variant(k, question_type, _STRENGTH) for k, v in ordered_high if v >= strong][:3]
    explained = signals.concepts.with_status("demonstrated") if getattr(signals, "concepts", None) else []
    if len(explained) >= 2 and not signals.keyword_list:
        strengths.insert(0, f"You explained {len(explained)} key concepts, including {explained[0]} and {explained[1]}.")
        strengths = strengths[:3]
    if not strengths:
        strengths = [_MILD_PRAISE[ordered_high[0][0]]]

    weaknesses: list[str] = []
    if signals.keyword_list:
        weaknesses.append(_WEAKNESS["keyword_list"])
    for item in signals.misconceptions_found[:2]:
        weaknesses.append(f"Check this point: {item['explanation']}")
    for claim in getattr(signals, "unsupported_claims", [])[:1]:
        weaknesses.append(f"This claim needs support: “{claim}” Explain why it holds, or give an example.")
    for key, value in ordered_low:
        if value >= weak or len(weaknesses) >= 3:
            break
        if key in ("coverage", "correctness"):
            if signals.missing_key_points and not any("did not mention" in w for w in weaknesses):
                weaknesses.append(f"Some key concepts are missing. You did not mention: {'; '.join(signals.missing_key_points[:2])}.")
            continue
        if key == "communication":
            if signals.word_count < 50:
                weaknesses.append(_WEAKNESS["communication_short"])
            elif signals.word_count > 280:
                weaknesses.append(_WEAKNESS["communication_long"])
            else:
                weaknesses.append(_WEAKNESS["communication"])
            continue
        weaknesses.append(_variant(key, question_type, _WEAKNESS))
    weaknesses = list(dict.fromkeys(weaknesses))[:3]
    if not weaknesses:
        weaknesses = [_MINOR[ordered_low[0][0]]]

    suggestions = []
    for key, value in ordered_low:
        if value < strong and len(suggestions) < 3:
            suggestions.append(_variant(key, question_type, _SUGGESTION))
    if not suggestions:
        suggestions = [_variant(ordered_low[0][0], question_type, _SUGGESTION)]
    suggestions = list(dict.fromkeys(suggestions))
    return AnswerFeedback(strengths=strengths, weaknesses=weaknesses, tip=suggestions[0], suggestions=suggestions)


def explanation(*, dimensions, signals, engine_name: str, question_type: QuestionType, overall: int) -> str:
    applicable = [d for d in dimensions if d.score is not None and d.weight > 0]
    weights = ", ".join(f"{d.label.lower()} {round(d.weight * 100)}%" for d in applicable)
    parts = [
        f"Overall {overall}/100 is a weighted average for a {question_type.value} question ({weights}).",
        f"Concept coverage looks for each rubric concept explained in your own sentences ({len(signals.covered_key_points)} of "
        f"{len(signals.covered_key_points) + len(signals.missing_key_points)} found); naming a term in a list is not counted as explaining it.",
        f"Text similarity ({engine_name}) is used only as supporting evidence for relevance, not as proof of correctness.",
    ]
    if question_type is QuestionType.BEHAVIORAL:
        parts.append("Technical accuracy is not scored for behavioral questions.")
    level = getattr(signals, "evidence_level", "sufficient")
    if level == "insufficient":
        parts.append("There was too little relevant content to judge your knowledge here, so treat low scores as "
                     "'not shown yet' rather than as a lack of skill.")
    elif level == "limited":
        parts.append("The answer was short or mostly a list of terms, so this score rests on limited evidence and "
                     "could change with a fuller explanation.")
    parts.append("This is an automated estimate for practice, not a judgement of your real-world ability.")
    return " ".join(parts)


