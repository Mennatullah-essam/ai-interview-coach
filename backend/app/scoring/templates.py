"""Rule-based feedback text (spec 16.4 steps H and J).

Every sentence comes from this fixed library and is chosen by a rule, so each
piece of feedback can be traced to a criterion. Nothing is generated by AI.
The templates describe coverage, structure and clarity; they never claim an
answer is factually correct or incorrect.
"""

from dataclasses import dataclass, field

from app.models.enums import QuestionType

# --- per-answer feedback -------------------------------------------------------

