"""Interview intelligence: explainable question planning from the curated bank.

Inputs: the interview settings (role, type, difficulty, count), the role's
requirement profile (app/data/roles.json), skills found in an optional job
description, and, only if the candidate confirmed it, their reviewed profile
(skills, projects, level). Without a profile it falls back to the CV skills,
exactly like Milestone 3.

Rules (all deterministic for a given interview id):
1. Respect the settings: question type mix (mixed = 60/40), count, and the
   chosen difficulty first (then adjacent levels, preferring easier ones for
   entry-level candidates and harder ones for senior candidates).
2. Rank bank questions by requirement fit, the candidate's skills and semantic
   similarity to the role/job description (embedding model when loaded,
   otherwise the lexical engine), with a bonus for role-specific questions.
3. Build a balanced plan: core role questions, a few CV-skill and project
   questions, and skill-gap checks for required skills the candidate has not
   shown, plus behavioral questions spread across different competencies.
4. Avoid repetition: unique texts, and a penalty for questions that test the
   same skills as ones already chosen.
5. Every question records why it was chosen and which skills it assesses.
7. Milestone 5: retrieval documents include rubric points and competency
   descriptions (intelligence/retrieval.py); maximal-marginal-relevance avoids
   near-duplicate questions; questions from the user's earlier interviews are
   penalised; a coverage pass assesses several different required skills,
   prioritising those the interview evidence marks as weak or unassessed.
6. No partial interviews: QUESTION_BANK_INSUFFICIENT if the bank is too small.
Nothing is generated by a language model; templates are filled from the
candidate's own CV or profile.
"""

import random
import re
from dataclasses import dataclass, field

from app.core.errors import AppError
from app.models import QuestionBankItem
from app.models.enums import Difficulty, InterviewType, QuestionKind, QuestionType
from app.services.question_bank import PRESET_ROLES

MIXED_TECHNICAL_SHARE = 0.6
DIVERSITY_PENALTY = 0.15
REDUNDANCY_WEIGHT = 0.35  # weight of the closest already-chosen question's similarity (MMR)
# Repeats are ranked like a difficulty mismatch: a question from the previous interview ranks
# below an unseen question one difficulty level away; an older repeat ranks between the two.
REPEAT_PENALTY_LAST = 1.1
REPEAT_PENALTY_OLDER = 0.6
NEAR_DUPLICATE = 0.8  # similarity above which a question counts as a near-duplicate of a chosen one
_DIFFICULTY_ORDER = [Difficulty.BEGINNER, Difficulty.INTERMEDIATE, Difficulty.ADVANCED]
_ROLE_STOPWORDS = {"engineer", "developer", "senior", "junior", "lead", "intern", "specialist", "and", "of", "the"}
_ROLE_SYNONYMS = {
    "ml": "Machine Learning Engineer", "mlops": "Machine Learning Engineer",
    "ai": "AI Engineer", "nlp": "AI Engineer", "llm": "AI Engineer", "genai": "AI Engineer",
    "vision": "AI Engineer", "deep": "AI Engineer",
    "web": "Frontend Developer", "ui": "Frontend Developer", "react": "Frontend Developer",
    "javascript": "Frontend Developer",
    "api": "Backend Developer", "server": "Backend Developer", "python": "Backend Developer",
    "java": "Backend Developer", "devops": "Backend Developer", "cloud": "Backend Developer",
    "bi": "Data Analyst", "analytics": "Data Analyst", "business": "Data Analyst",
    "statistician": "Data Scientist", "research": "Data Scientist", "researcher": "Data Scientist",
    "software": "Software Engineer", "fullstack": "Software Engineer", "full": "Software Engineer",
    "mobile": "Software Engineer", "programmer": "Software Engineer",
}


@dataclass
class SelectedQuestion:
    text: str
    question_type: QuestionType
    ideal_answer: str
    key_points: list[str]
    bank_question_id: object
    category: str = "core"
    reason: str = ""
    focus_skills: list[str] = field(default_factory=list)
    misconceptions: list[dict] = field(default_factory=list)


@dataclass
class PlanContext:
    """Everything the planner knows about the role and the candidate."""

    roles: set[str]
    role_label: str
    required: list[str] = field(default_factory=list)
    preferred: list[str] = field(default_factory=list)
    job_skills: list[str] = field(default_factory=list)
    candidate_skills: list[str] = field(default_factory=list)
    projects: list[str] = field(default_factory=list)
    gaps: list[str] = field(default_factory=list)
    level: str | None = None
    personalized: bool = False
    target_text: str = ""
    related: list[str] = field(default_factory=list)  # neighbours of required skills (competency graph)


def round_half_up(value: float) -> int:
    return int(value + 0.5) if value >= 0 else -int(-value + 0.5)


def match_roles(target_role: str) -> set[str]:
    role = target_role.strip().lower()
    for preset in PRESET_ROLES:
        if preset.lower() == role:
            return {preset}
    words = {w for w in re.findall(r"[a-z0-9]+", role) if w not in _ROLE_STOPWORDS}
    matched = {_ROLE_SYNONYMS[w] for w in words if w in _ROLE_SYNONYMS}
    for preset in PRESET_ROLES:
        preset_words = {w for w in re.findall(r"[a-z0-9]+", preset.lower()) if w not in _ROLE_STOPWORDS}
        if words & preset_words:
            matched.add(preset)
    return matched


def _type_counts(interview_type: InterviewType, n: int) -> dict[QuestionType, int]:
    if interview_type is InterviewType.TECHNICAL:
        return {QuestionType.TECHNICAL: n}
    if interview_type is InterviewType.BEHAVIORAL:
        return {QuestionType.BEHAVIORAL: n}
    technical = round_half_up(n * MIXED_TECHNICAL_SHARE)
    return {QuestionType.TECHNICAL: technical, QuestionType.BEHAVIORAL: n - technical}


def _difficulty_rank(item: Difficulty | None, wanted: Difficulty, level: str | None) -> float:
    if item is None:
        return 1.0
    distance = _DIFFICULTY_ORDER.index(item) - _DIFFICULTY_ORDER.index(wanted)
    rank = float(abs(distance))
    # When relaxing difficulty, lean towards the candidate's level.
    if distance and level in ("student", "entry", "junior"):
        rank += 0.1 if distance > 0 else 0.0
    elif distance and level == "senior":
        rank += 0.1 if distance < 0 else 0.0
    return rank


def _role_ok(item: QuestionBankItem, roles: set[str]) -> bool:
    tags = set(item.role_tags or [])
    return "general" in tags or bool(tags & roles)


def insufficient() -> AppError:
    return AppError(
        "QUESTION_BANK_INSUFFICIENT",
        "There are not enough questions for these settings. Try fewer questions or another interview type.",
        422,
    )


def _lower(items) -> set[str]:
    return {s.lower() for s in items}


def build_context(
    *,
    target_role: str,
    cv_skills: list[str],
    profile=None,
    job_description: str | None = None,
) -> PlanContext:
    """Combine role requirements, the job description and the candidate's data."""
    from app.intelligence.knowledge import find_alias_skills, role_requirements
    from app.services.cv_parsing import find_skills, load_skills
    from app.core.config import get_settings

    roles = match_roles(target_role)
    requirements = role_requirements(roles)
    job_skills: list[str] = []
    if job_description:
        vocabulary = load_skills(get_settings().skills_list_path)
        job_skills = list(dict.fromkeys([*find_skills(job_description, vocabulary, limit=40), *find_alias_skills(job_description)]))
    required = list(dict.fromkeys([*(requirements.required_skills if requirements else ()), *job_skills]))
    preferred = [s for s in (requirements.preferred_skills if requirements else ()) if s not in required]

    if profile is not None:
        candidate = [s.name for s in profile.technical_skills]
        projects = [p.name for p in profile.projects if p.name]
        level = profile.experience_level.value
    else:
        candidate, projects, level = list(cv_skills), [], None
    have = _lower(candidate)
    # Gaps are only claimed when we actually know the candidate's skills.
    gaps = [s for s in required if s.lower() not in have] if (profile is not None or cv_skills) else []

    from app.intelligence.competencies import competency_model

    model = competency_model()
    related = [r for s in required for r in model.related(s) if r.lower() not in _lower(required)]
    target_text = " ".join(filter(None, [
        target_role,
        requirements.description if requirements else "",
        " ".join(required),
        " ".join(model.description(s) for s in required),
        (job_description or "")[:2000],
    ]))
    return PlanContext(
        roles=roles,
        role_label=target_role,
        required=required,
        preferred=preferred,
        job_skills=job_skills,
        candidate_skills=candidate,
        projects=projects,
        gaps=gaps,
        level=level,
        personalized=profile is not None,
        target_text=target_text,
        related=list(dict.fromkeys(related)),
    )


def _engine():
    """The loaded similarity engine (sbert or lexical); lexical if none is usable."""
    from app.scoring.similarity import EngineUnavailable, LexicalSimilarity, get_engine

    try:
        return get_engine()
    except EngineUnavailable:
        return LexicalSimilarity()


def _doc(q: QuestionBankItem) -> str:
    from app.intelligence.retrieval import question_document

    return question_document(q.text, list(q.key_points or []), list(q.skill_tags or []))


# Interview evidence changes priorities only when the candidate has history.
_NEED_BONUS = {"weak": 0.18, "needs_evidence": 0.12, "unassessed": 0.08, "developing": 0.04, "demonstrated": -0.08}


def _relevance(q: QuestionBankItem, ctx: PlanContext, index, ledger=None) -> float:
    tags = _lower(q.skill_tags or [])
    role_specific = bool(set(q.role_tags or []) & ctx.roles)
    required_hits = len(tags & _lower(ctx.required))
    preferred_hits = len(tags & _lower(ctx.preferred))
    candidate_hits = len(tags & _lower(ctx.candidate_skills))
    related_hits = len(tags & _lower(ctx.related)) if not required_hits else 0
    semantic = index.similarity(_doc(q), ctx.target_text) if ctx.target_text else 0.0
    need = 0.0
    if ledger is not None and ledger.items:
        need = max((_NEED_BONUS[ledger.status(t)] for t in (q.skill_tags or []) if t.lower() in _lower(ctx.required)),
                   default=0.0)
    return (
        0.35 * role_specific
        + 0.25 * min(required_hits, 2)
        + 0.10 * min(preferred_hits, 2)
        + 0.15 * min(candidate_hits, 2)
        + 0.08 * min(related_hits, 2)
        + 0.50 * semantic
        + need
    )


def _evidence_note(skill: str, ledger) -> str:
    if ledger is None or not ledger.items:
        return ""
    entry = ledger.items.get(f"skill:{skill}")
    status = ledger.status(skill)
    if status == "unassessed":
        return " It has not been assessed in your earlier interviews."
    if status in ("weak", "needs_evidence") and entry is not None:
        return f" Earlier answers on it averaged {entry.average}/100, so it is worth another look."
    return ""


def _reason_core(q: QuestionBankItem, ctx: PlanContext, semantic: float = 0.0) -> tuple[str, list[str]]:
    tags = list(q.skill_tags or [])
    focus = [t for t in tags if t.lower() in _lower(ctx.required)] or tags[:2]
    role_specific = bool(set(q.role_tags or []) & ctx.roles)
    parts = [f"Core {ctx.role_label} question" if role_specific else "General technical question"]
    if focus:
        parts[0] += f" on {', '.join(focus[:3])}"
    matched = [t for t in tags if t.lower() in _lower(ctx.candidate_skills)]
    if matched:
        parts.append(f"it builds on skills you listed ({', '.join(matched[:3])})")
    elif any(t.lower() in _lower(ctx.job_skills) for t in tags):
        parts.append("it covers skills named in the job description")
    elif ctx.job_skills and semantic >= 0.25:
        parts.append("its topic is close to your job description")
    return "; ".join(parts) + ".", focus[:4]


def select_questions(
    bank: list[QuestionBankItem],
    *,
    target_role: str,
    interview_type: InterviewType,
    difficulty: Difficulty,
    question_count: int,
    cv_skills: list[str],
    seed: str,
    profile=None,
    job_description: str | None = None,
    engine=None,
    history: list[str] | None = None,
    ledger=None,
) -> list[SelectedQuestion]:
    """Plan an interview. `history` = question texts from the user's earlier interviews,
    most recent first; `ledger` = their competency evidence (see intelligence.competencies)."""
    from app.intelligence.retrieval import get_index

    rng = random.Random(seed)
    ctx = build_context(target_role=target_role, cv_skills=cv_skills, profile=profile, job_description=job_description)
    index = get_index(engine or _engine())
    used_texts: set[str] = set()
    by_type: dict[QuestionType, list[SelectedQuestion]] = {}
    # How recently a question was asked: 0 = in the last interview, 1 = before that.
    recency: dict[str, int] = {}
    for position, text in enumerate(history or []):
        recency.setdefault(text.lower(), 0 if position < 15 else 1)

    # Candidate skills, most role-relevant first, for CV-skill templates.
    skill_pool = sorted(ctx.candidate_skills, key=lambda s: (s.lower() not in _lower(ctx.required),
                                                              s.lower() not in _lower(ctx.preferred), rng.random()))
    project_pool = list(ctx.projects)

    for qtype, count in _type_counts(interview_type, question_count).items():
        chosen: list[SelectedQuestion] = []
        active = [q for q in bank if q.is_active and q.question_type is qtype and _role_ok(q, ctx.roles) and q.ideal_answer]

        def add(text, q, category, reason, focus, ideal=None, key_points=None):
            used_texts.add(text.lower())
            chosen.append(SelectedQuestion(
                text=text, question_type=qtype, ideal_answer=ideal or q.ideal_answer,
                key_points=key_points or list(q.key_points or []), bank_question_id=q.id,
                category=category, reason=reason, focus_skills=focus, misconceptions=list(q.misconceptions or []),
            ))

        if qtype is QuestionType.TECHNICAL and count >= 3:
            # Project questions from the reviewed profile.
            project_templates = [q for q in active if q.kind is QuestionKind.PROJECT_TEMPLATE]
            rng.shuffle(project_templates)
            project_slots = min(len(project_templates), len(project_pool), 1 if count < 10 else 2) if ctx.personalized else 0
            for template in project_templates[:project_slots]:
                project = project_pool.pop(0)
                fill = lambda s, p=project: s.replace("{project}", p)  # noqa: E731
                add(fill(template.text), template, "project", f"From your project “{project}” in your profile.",
                    [project], fill(template.ideal_answer), [fill(k) for k in template.key_points])

            # CV-skill templates: at most one per skill, about one in four questions.
            skill_templates = [q for q in active if q.kind is QuestionKind.SKILL_TEMPLATE]
            rng.shuffle(skill_templates)
            skill_slots = min(len(skill_templates), len(skill_pool), max(1, count // 4))
            for template in skill_templates[:skill_slots]:
                skill = skill_pool.pop(0)
                fill = lambda s, k=skill: s.replace("{skill}", k)  # noqa: E731
                text = fill(template.text)
                if text.lower() in used_texts:
                    continue
                note = f", which {ctx.role_label} roles expect" if skill.lower() in _lower(ctx.required) else ""
                add(text, template, "cv_skill", f"From your CV: you list {skill}{note}.", [skill],
                    fill(template.ideal_answer), [fill(k) for k in template.key_points])

        generic = [q for q in active if q.kind is QuestionKind.GENERIC]
        scores = {q.id: _relevance(q, ctx, index, ledger) for q in generic}
        semantic = {q.id: index.similarity(_doc(q), ctx.target_text) if ctx.target_text else 0.0 for q in generic}
        tiebreak = {q.id: rng.random() for q in generic}
        covered: dict[str, int] = {}
        picked_docs: list[str] = [c.text for c in chosen]

        def pick(pool, limit):
            picked = []
            while len(picked) < limit:
                remaining = [q for q in pool if q.text.lower() not in used_texts]
                if not remaining:
                    break
                redundancy = {q.id: max((index.similarity(_doc(q), d) for d in picked_docs), default=0.0)
                              for q in remaining}
                # Near-duplicates of chosen questions are skipped whenever anything else is left.
                distinct = [q for q in remaining if redundancy[q.id] < NEAR_DUPLICATE]
                remaining = distinct or remaining

                def key(q):
                    overlap = sum(covered.get(t.lower(), 0) for t in (q.skill_tags or []))
                    # Maximal marginal relevance: penalise questions too close to ones already chosen.
                    value = scores[q.id] - DIVERSITY_PENALTY * overlap - REDUNDANCY_WEIGHT * redundancy[q.id]
                    repeat = {0: REPEAT_PENALTY_LAST, 1: REPEAT_PENALTY_OLDER}.get(recency.get(q.text.lower()), 0.0)
                    return (_difficulty_rank(q.difficulty, difficulty, ctx.level) + repeat, -value, tiebreak[q.id])
                best = min(remaining, key=key)
                for t in best.skill_tags or []:
                    covered[t.lower()] = covered.get(t.lower(), 0) + 1
                picked.append(best)
                picked_docs.append(_doc(best))
                used_texts.add(best.text.lower())
            return picked

        def note_repeat(q) -> str:
            return " You saw it in an earlier interview; few unseen questions fit these settings." \
                if q.text.lower() in recency else ""

        if qtype is QuestionType.TECHNICAL and ctx.gaps and (ctx.personalized or ctx.job_skills) and count - len(chosen) >= 3:
            gap_set = _lower(ctx.gaps)
            gap_pool = [q for q in generic if _lower(q.skill_tags or []) & gap_set]
            for q in pick(gap_pool, max(1, count // 5)):
                gaps = [t for t in q.skill_tags if t.lower() in gap_set]
                source = " and the job description" if any(g.lower() in _lower(ctx.job_skills) for g in gaps) else ""
                add(q.text, q, "skill_gap",
                    f"Skill-gap check: {', '.join(gaps[:2])} {'is' if len(gaps[:2]) == 1 else 'are'} expected for "
                    f"{ctx.role_label}{source} but not in your profile yet.", gaps[:3])

        if qtype is QuestionType.TECHNICAL and ctx.required and count - len(chosen) >= 2:
            # Competency coverage: make sure several different required skills are assessed,
            # starting with those the candidate's interview evidence says need it most.
            order = {"weak": 0, "needs_evidence": 1, "unassessed": 2, "developing": 3, "demonstrated": 4}
            assessed = {t.lower() for c in chosen for t in c.focus_skills}
            targets = sorted(
                [r for r in ctx.required if r.lower() not in assessed],
                key=lambda r: (order[ledger.status(r)] if ledger is not None and ledger.items else 2,
                               ctx.required.index(r)),
            )
            slots = max(1, count // 3)
            for skill in targets:
                if slots <= 0:
                    break
                if skill.lower() in {t.lower() for c in chosen for t in c.focus_skills}:
                    continue
                pool = [q for q in generic if skill.lower() in _lower(q.skill_tags or [])]
                found = pick(pool, 1)
                if not found:
                    continue
                q = found[0]
                slots -= 1
                focus = [skill] + [t for t in q.skill_tags if t.lower() in _lower(ctx.required) and t != skill][:2]
                add(q.text, q, "coverage",
                    f"Covers {skill}, a core skill for {ctx.role_label}.{_evidence_note(skill, ledger)}{note_repeat(q)}",
                    focus)

        for q in pick(generic, count - len(chosen)):
            if qtype is QuestionType.BEHAVIORAL:
                competencies = list(q.skill_tags or [])
                reason = (f"Behavioral question assessing {', '.join(c.lower() for c in competencies[:2])}."
                          if competencies else "Behavioral question.")
                add(q.text, q, "behavioral", reason + note_repeat(q), competencies[:3])
            else:
                reason, focus = _reason_core(q, ctx, semantic[q.id])
                add(q.text, q, "core", reason + note_repeat(q), focus)

        if len(chosen) < count:
            raise insufficient()
        chosen = chosen[:count]
        rng.shuffle(chosen)
        by_type[qtype] = chosen

    if len(by_type) == 1:
        return next(iter(by_type.values()))
    # Mixed: spread behavioral questions evenly between technical ones.
    technical = by_type[QuestionType.TECHNICAL]
    behavioral = by_type[QuestionType.BEHAVIORAL]
    ordered = []
    b_total = len(behavioral)
    total = len(technical) + b_total
    for i in range(total):
        # Place the k-th behavioral question where floor(position * share) steps up.
        want_behavioral = (i + 1) * b_total // total > i * b_total // total
        ordered.append(behavioral.pop(0) if want_behavioral else technical.pop(0))
    return ordered
